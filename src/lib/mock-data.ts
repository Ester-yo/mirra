export function matchProduct(raw: string) {
  const url = raw.trim();
  if (!url || !(/https?:\/\//i.test(url) || /amazon|tiktok|shop|item/i.test(url))) return null;
  const lower = url.toLowerCase();
  return PRODUCTS.find((item) => item.keywords.some((key) => lower.includes(key))) ?? PRODUCTS[PRODUCTS.length - 1];
}

